'use strict';

// Plugin-publisher contracts, translated into the local CCode identity.
//
// The published plugin ecosystem is written against the upstream product name:
// the official marketplace CDN declares its marketplace id in that spelling,
// plugin zips ship their manifest inside that product's `.<name>-plugin`
// directory, and plugin runtimes read `<PREFIX>_PLUGIN_ROOT`-style variables.
// Those names belong to the publishers, so they keep the upstream spelling and
// this module meets them at the boundary, translating them into CCode names so
// nothing upstream reaches the local state or the interface.
//
// Generated by src/local_only/marketplace.py: the six `REMOTE` values below are
// filled from rebrand.previous(), so the upstream spelling stays written down
// once, in src/local_only/rebrand.py, and never in a tracked source file.
//
// The second job here is language: published payloads carry Chinese labels and
// skill descriptions with no English variant, which would surface in the plugin
// detail panel and in the skill list the agent reads. `localizePluginTree`
// rewrites only those fields, in place, in the resolved plugin copy.

const fs = require('node:fs');
const path = require('node:path');

const LOCAL = {
  marketplaceId: 'ccode-plugins-official',
  manifestDir: '.ccode-plugin',
  envPrefix: 'CCODE_',
  product: { upper: 'CCODE', title: 'CCode', mixed: 'Ccode', lower: 'ccode' },
};

const REMOTE = {
  marketplaceId: '__REMOTE_MARKETPLACE_ID__',
  manifestDir: '__REMOTE_MANIFEST_DIR__',
  envPrefix: '__REMOTE_ENV_PREFIX__',
  product: {
    upper: '__REMOTE_PRODUCT_UPPER__',
    title: '__REMOTE_PRODUCT_TITLE__',
    mixed: '__REMOTE_PRODUCT_MIXED__',
    lower: '__REMOTE_PRODUCT_LOWER__',
  },
};

const MANIFEST_NAME = 'plugin.json';
const SKILL_NAME = 'SKILL.md';
const URL_RUN = /https?:\/\/[^\s"'`<>)\]}\\]+/g;
const MASK = '\u0000url-';
const CJK_SOURCE = '[\u3000-\u303f\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\uff01-\uff60\uffe0-\uffee]';
const CJK_RUN = new RegExp(CJK_SOURCE, 'g');
const CJK_TEST = new RegExp(CJK_SOURCE);
// Skill descriptions live in YAML frontmatter; only these keys are rewritten.
const FRONTMATTER_TEXT_KEYS = ('description when_to_use').split(' ');

function officialIds() {
  return [LOCAL.marketplaceId, REMOTE.marketplaceId];
}

function acceptOfficialName(name) {
  return officialIds().includes(name);
}

/** Rewrite a manifest that a trusted source published under the upstream id. */
function adoptOfficialName(manifest, trustedId) {
  if (!manifest || typeof manifest !== 'object') return manifest;
  const id = typeof trustedId === 'string' && trustedId ? trustedId : LOCAL.marketplaceId;
  manifest.name = id;
  if (manifest.raw && typeof manifest.raw === 'object') manifest.raw.name = id;
  return manifest;
}

/** Manifest locations inside a plugin root: the local dir first, then the published one. */
function manifestFiles(base) {
  const files = [];
  for (const entry of [...(Array.isArray(base) ? base : []), `${LOCAL.manifestDir}/${MANIFEST_NAME}`,
    `${REMOTE.manifestDir}/${MANIFEST_NAME}`]) {
    if (typeof entry === 'string' && entry && !files.includes(entry)) files.push(entry);
  }
  return files;
}

function isFile(candidate) {
  try {
    return fs.statSync(candidate).isFile();
  } catch {
    return false;
  }
}

function manifestAt(root) {
  return manifestFiles([]).some(relative => isFile(path.join(root, relative)));
}

function findManifest(root) {
  return manifestPathIn(root, []);
}

/** Manifest file for a plugin root, for call sites that join their own constants. */
function manifestPathIn(root, base) {
  for (const relative of manifestFiles(base)) {
    const candidate = path.join(root, relative);
    if (isFile(candidate)) return candidate;
  }
  return null;
}

/** `${<PUBLISHER>_PLUGIN_ROOT}` and friends, for payloads written to the published runtime. */
function resolveRemoteVar(name, ctx) {
  if (typeof name !== 'string' || !name.startsWith(REMOTE.envPrefix)) return undefined;
  const leaf = name.slice(REMOTE.envPrefix.length);
  if (leaf === 'PLUGIN_ROOT') return ctx.loaded.rootPath;
  if (leaf === 'PLUGIN_DATA') return ctx.dataPath;
  if (leaf === 'PLUGIN_ID') return ctx.loaded.id;
  if (leaf === 'PLUGIN_NAME') return ctx.loaded.name;
  if (leaf === 'PROJECT_DIR') return ctx.workingDirectory;
  if (leaf === 'SESSION_ID' || leaf === 'SKILL_DIR') {
    throw new Error(`Plugin variable requires a runtime context: ${name}`);
  }
  return undefined;
}

/** The same variables under the published prefix, for plugin processes that read them. */
function envAliases(ctx = {}) {
  const aliases = {};
  const put = (leaf, value) => {
    if (typeof value === 'string' && value) aliases[REMOTE.envPrefix + leaf] = value;
  };
  put('PLUGIN_ROOT', ctx.rootPath);
  put('PLUGIN_DATA', ctx.dataPath);
  put('PLUGIN_ID', ctx.id);
  put('PLUGIN_NAME', ctx.name);
  put('PROJECT_DIR', ctx.workingDirectory);
  return aliases;
}

/** Upstream product mentions in published display text; URLs are contracts and stay put. */
function localizeText(text) {
  if (typeof text !== 'string' || !text) return text;
  const urls = [];
  const masked = text.replace(URL_RUN, match => {
    urls.push(match);
    return `${MASK}${urls.length - 1}\u0000`;
  });
  const localized = Object.keys(REMOTE.product)
    .reduce((text, key) => text.split(REMOTE.product[key]).join(LOCAL.product[key]), masked);
  if (!urls.length) return localized;
  return localized.replace(new RegExp(`${MASK}(\\d+)\u0000`, 'g'), (_match, index) => urls[Number(index)]);
}

function hasCjk(value) {
  return typeof value === 'string' && CJK_TEST.test(value);
}

function cjkCount(value) {
  return (String(value).match(CJK_RUN) || []).length;
}

function latinCount(value) {
  return (String(value).match(/[A-Za-z]/g) || []).length;
}

function stripCjk(value) {
  return String(value)
    .replace(CJK_RUN, ' ')
    .replace(/\s+/g, ' ')
    .replace(/^[\s:：,，、.·\-–—|]+|[\s:：,，、.·\-–—|]+$/g, '')
    .trim();
}

function repairPunctuation(text) {
  return text
    .replace(/\(\s*(?:e\.g\.)?\s*\)/g, '')
    .replace(/\s*\bor\s*(?=[.,;)]|$)/g, '')
    .replace(/\s*,\s*(?=[,.;)])/g, '')
    .replace(/\s+([,;)])/g, '$1')
    .replace(/,(\s*[)'"])/g, '$1')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

/**
 * Remove the Chinese keyword tokens a published description uses as extra triggers,
 * keeping the words around them: `'Excel/CSV/数据分析/报表/汇总'` keeps `'Excel/CSV'`
 * and a quoted `'PPT转PDF'` disappears whole.
 */
function stripCjkTokens(text) {
  const slashRun = new RegExp(`[^\\s,;("']+(?:/[^\\s,;("']+)+`, 'g');
  const quotedToken = new RegExp(`["'][^"'\\s]*${CJK_SOURCE}[^"'\\s]*["']`, 'g');
  const listItem = new RegExp(`,\\s*[^,;:\\n()"']*${CJK_SOURCE}[^,;:\\n()"']*`, 'g');
  let out = text.replace(slashRun, run => {
    const kept = run.split('/').filter(token => !(CJK_TEST.test(token) && latinCount(token) <= 2));
    return kept.length ? kept.join('/') : run;
  });
  out = out.replace(quotedToken, '');
  out = out.replace(listItem, item => (latinCount(item) <= 2 ? '' : item));
  return repairPunctuation(out);
}

/**
 * The English text that replaces a published description written in Chinese, or null
 * when the published text should be kept as it is.
 */
function deChineseDescription(value, fallback) {
  const localized = localizeText(value);
  if (!hasCjk(localized)) return localized === value ? null : localized;
  const cjk = cjkCount(localized);
  // A description published in Chinese cannot be translated here; the plugin's own
  // English description stands in for it.
  if (cjk * 2 >= cjk + latinCount(localized)) return fallback || stripCjk(localized) || null;
  const cleaned = stripCjkTokens(localized);
  // English text that merely carried Chinese trigger tokens: accept the cleanup only
  // when every Chinese character is gone, so a sentence is never left half-translated.
  if (cleaned && cleaned !== localized && !hasCjk(cleaned)) return cleaned;
  return null;
}

/** A readable English label for a configuration key whose published label was Chinese. */
function humanizeKey(key) {
  return String(key)
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()
    .replace(/^./, character => character.toUpperCase());
}

function englishVariant(value, i18n) {
  if (!i18n || typeof i18n !== 'object') return null;
  for (const locale of ['en', 'en-US', 'en_US', 'en-GB']) {
    const candidate = i18n[locale];
    if (typeof candidate === 'string' && candidate.trim() && !hasCjk(candidate)) return candidate;
  }
  return null;
}

function localizeConfigField(field, key) {
  if (!field || typeof field !== 'object') return;
  if (typeof field.title === 'string') {
    const localized = localizeText(field.title);
    // A published label that is Chinese is replaced by the field's own name, so the
    // settings form stays readable instead of keeping a half-translated string.
    if (hasCjk(localized) || localized !== field.title) field.title = humanizeKey(key);
  }
  if (typeof field.description !== 'string') return;
  const localized = localizeText(field.description);
  // A published description that is Chinese is dropped rather than half-stripped:
  // the leftover keywords of a translated sentence can invert its meaning.
  if (hasCjk(localized)) delete field.description;
  else if (localized !== field.description) field.description = localized;
}

function localizeSurfaceTitle(surface, index) {
  if (!surface || typeof surface !== 'object' || typeof surface.title !== 'string') return;
  const localized = localizeText(surface.title);
  if (!hasCjk(localized)) {
    if (localized !== surface.title) surface.title = localized;
    return;
  }
  surface.title = stripCjk(localized) || humanizeKey(surface.id || `panel ${index + 1}`);
}

/** Rewrite the published labels of one plugin manifest in place; idempotent. */
function localizeManifest(manifest) {
  if (!manifest || typeof manifest !== 'object') return manifest;
  const english = englishVariant(manifest.description, manifest.description_i18n);
  if (typeof manifest.description === 'string' && hasCjk(manifest.description)) {
    const replacement = english ?? stripCjk(manifest.description);
    if (replacement) manifest.description = replacement;
    else delete manifest.description;
  } else if (typeof manifest.description === 'string') {
    manifest.description = localizeText(manifest.description);
  }
  if (typeof manifest.displayName === 'string') {
    const localized = localizeText(manifest.displayName);
    if (hasCjk(localized)) {
      const english = englishVariant(manifest.displayName, manifest.displayName_i18n);
      manifest.displayName = english || stripCjk(localized) || manifest.displayName;
    } else {
      manifest.displayName = localized;
    }
  }
  if (manifest.author && typeof manifest.author === 'object' && typeof manifest.author.name === 'string') {
    manifest.author.name = localizeText(manifest.author.name);
  }
  if (manifest.userConfig && typeof manifest.userConfig === 'object') {
    for (const [key, field] of Object.entries(manifest.userConfig)) localizeConfigField(field, key);
  }
  const surfaces = manifest.ui && typeof manifest.ui === 'object' ? manifest.ui.surfaces : null;
  if (Array.isArray(surfaces)) surfaces.forEach(localizeSurfaceTitle);
  return manifest;
}

/** Marketplace entry lists: published display text, in English and without Chinese defaults. */
function localizeEntry(entry) {
  if (!entry || typeof entry !== 'object') return entry;
  for (const [field, i18nField] of [['displayName', 'displayName_i18n'], ['description', 'description_i18n']]) {
    if (typeof entry[field] !== 'string') continue;
    if (hasCjk(entry[field])) {
      const english = englishVariant(entry[field], entry[i18nField]);
      const stripped = english || stripCjk(entry[field]);
      if (stripped) entry[field] = stripped;
      else if (field === 'displayName') entry[field] = humanizeKey(entry.name || 'plugin');
      else delete entry[field];
    }
    if (typeof entry[field] === 'string') entry[field] = localizeText(entry[field]);
  }
  if (typeof entry.category === 'string') entry.category = localizeText(entry.category);
  // A published plugin whose own name carries the upstream spelling has no display
  // name to fall back on, so the list would show that spelling: give it one in the
  // local spelling. The identity itself stays as published - install paths, the
  // manifest inside the zip and `plugin://` references all use the published name.
  if (typeof entry.displayName !== 'string' && typeof entry.name === 'string') {
    const localizedName = localizeText(entry.name);
    if (localizedName !== entry.name) entry.displayName = localizedName;
  }
  for (const field of ['displayName_i18n', 'description_i18n', 'examplePrompts_i18n']) {
    const map = entry[field];
    if (!map || typeof map !== 'object') continue;
    for (const locale of Object.keys(map)) {
      if (typeof map[locale] === 'string') map[locale] = localizeText(map[locale]);
    }
  }
  for (const field of ['examplePrompts']) {
    if (Array.isArray(entry[field])) entry[field] = entry[field].map(localizeText);
  }
  const author = entry.author;
  if (typeof author === 'string') entry.author = localizeText(author);
  else if (author && typeof author === 'object' && typeof author.name === 'string') author.name = localizeText(author.name);
  for (const field of ['agents', 'commands', 'skills', 'hooks']) {
    const group = entry[field];
    if (!group || typeof group !== 'object') continue;
    for (const item of Object.values(group)) {
      if (item && typeof item === 'object' && typeof item.description === 'string') {
        item.description = localizeText(item.description);
      }
    }
  }
  return entry;
}

function localizeManifestEntries(manifest) {
  if (!manifest || typeof manifest !== 'object' || !Array.isArray(manifest.plugins)) return manifest;
  for (const entry of manifest.plugins) localizeEntry(entry);
  if (typeof manifest.description === 'string') manifest.description = localizeText(manifest.description);
  const owner = manifest.owner;
  if (owner && typeof owner === 'object' && typeof owner.name === 'string') owner.name = localizeText(owner.name);
  return manifest;
}

function skillFiles(root, depth = 5) {
  const found = [];
  const walk = (directory, level) => {
    let entries;
    try {
      entries = fs.readdirSync(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue;
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (level < depth) walk(full, level + 1);
      } else if (entry.isFile() && entry.name === SKILL_NAME) {
        found.push(full);
      }
    }
  };
  walk(root, 0);
  return found;
}

function frontmatterEnd(text) {
  if (!text.startsWith('---')) return -1;
  const end = text.indexOf('\n---', 3);
  return end < 0 ? -1 : end;
}

function quoteYaml(value) {
  return JSON.stringify(value);
}

/**
 * Replace one frontmatter key with an English value.
 * Returns the new text, or null when the key is absent or already acceptable.
 */
function rewriteFrontmatterKey(text, end, key, replacement) {
  const head = text.slice(0, end);
  const pattern = new RegExp(`^(${key}\\s*:\\s*)([^\\n]*)$`, 'm');
  const match = pattern.exec(head);
  if (!match) return null;
  if (match[2].trim().startsWith('|') || match[2].trim().startsWith('>')) return null;
  const updated = `${match[1]}${quoteYaml(replacement)}`;
  return updated === match[0] ? null : text.replace(pattern, () => updated);
}

function localizeSkillFile(file, fallback) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    return false;
  }
  const end = frontmatterEnd(text);
  if (end < 0) return false;
  let updated = text;
  for (const key of FRONTMATTER_TEXT_KEYS) {
    const match = new RegExp(`^${key}\\s*:\\s*(.+)$`, 'm').exec(updated.slice(0, end));
    if (!match) continue;
    const value = match[1].replace(/^["']|["']$/g, '').trim();
    const replacement = deChineseDescription(value, fallback);
    if (!replacement || replacement.length < 2) continue;
    const rewritten = rewriteFrontmatterKey(updated, end, key, replacement);
    if (rewritten) updated = rewritten;
  }
  if (updated === text) return false;
  try {
    fs.writeFileSync(file, updated, 'utf8');
    return true;
  } catch {
    return false;
  }
}

function pluginFallbackDescription(manifest) {
  return englishVariant(manifest && manifest.description, manifest && manifest.description_i18n)
    || (typeof manifest.displayName === 'string' && !hasCjk(manifest.displayName) ? manifest.displayName : null);
}

/**
 * Localize one resolved plugin copy in place: published manifest labels and skill
 * frontmatter the interface and the agent read. Returns the number of files.
 */
function localizePluginTree(root) {
  if (typeof root !== 'string' || !root) return 0;
  let changed = 0;
  let manifest = null;
  const manifestPath = findManifest(root);
  if (manifestPath) {
    try {
      const parsed = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
        const before = JSON.stringify(parsed);
        manifest = localizeManifest(parsed);
        if (JSON.stringify(manifest) !== before) {
          fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
          changed += 1;
        }
      }
    } catch {
      manifest = null;
    }
  }
  const fallback = pluginFallbackDescription(manifest);
  for (const file of skillFiles(root)) {
    if (localizeSkillFile(file, fallback)) changed += 1;
  }
  return changed;
}

/** `ict()` result: localize the resolved copy before callers describe, validate or install it. */
function localizeResolved(resolved) {
  if (resolved && typeof resolved === 'object' && typeof resolved.path === 'string') {
    try {
      localizePluginTree(resolved.path);
    } catch {
      // A published payload that cannot be rewritten still installs as published.
    }
  }
  return resolved;
}

